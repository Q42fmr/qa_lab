"""Подвоєні переноси рядків: \\r\\r\\n замість \\r\\n.

Звідки береться: якщо файл із CRLF прочитати у рядок і записати через
Path.write_text() на Windows без newline="", то кожен \\n перетвориться на
\\r\\n — і вже наявний \\r\\n стане \\r\\r\\n. Кожен цикл правки подвоює
знову (\\r\\r\\r\\r\\n).

Наслідки: файл роздувається (+1 байт на рядок за цикл), а будь-який diff
показує ВЕСЬ файл як змінений — бо кожен рядок відрізняється. На рендер
сторінки не впливає (зайві \\r — це whitespace), але заважає ревʼю і
роздуває репозиторій.

Автофікс схлопує будь-яку кількість \\r перед \\n назад у один \\r\\n.
"""
import re

NAME = "Подвоєні переноси рядків (\\r\\r\\n)"
# tests, а не auto: масовий автофікс переписав би пів-репозиторію одним
# комітом. Фікс лишається доступним вручну — fixable не залежить від групи.
GROUP = "tests"
# branch-code (branch_code.py): класи клієнтських даних, які цей
# чек МОЖЕ переписати — захищена вітка вимикає його цілком
MODIFIES = set()
PROJECTS = ["php"]
DESCRIPTION = ("Ловить файли з подвоєними \\r (\\r\\r\\n замість \\r\\n) — від них "
               "файл роздувається і весь diff показується як змінений. "
               "Автофікс схлопує їх назад у \\r\\n.")
FILES = ["*.html", "*.htm", "*.php", "*.css", "*.js", "*.xml", "*.txt",
         "*.json", "*.vue", "*.ts"]

# два і більше \r підряд перед \n
RX = re.compile(r"\r{2,}\n")


def run(path, text):
    hits = list(RX.finditer(text))
    if not hits:
        return []
    # найгірший випадок: скільки \r підряд трапляється
    worst = max(len(m.group(0)) - 1 for m in hits)
    line = text.count("\n", 0, hits[0].start()) + 1
    return [{
        "line": line,
        "severity": "warn",
        "message": f"подвоєні переноси рядків: {len(hits)} шт "
                   f"(до {worst} символів \\r підряд) — файл роздутий, "
                   f"diff показує весь файл зміненим; є автофікс",
    }]


def fix(path, text):
    """Схлопує \\r\\r\\n (і більше) назад у \\r\\n."""
    return RX.sub("\r\n", text)
