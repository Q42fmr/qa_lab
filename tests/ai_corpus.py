def cases(ptype: str | None = None, part: str = "all") -> list[dict]:
    """`part`: all | tuned | held_out. Розділяти обов'язково — на `tuned`
    скорер відповідає на власну шпаргалку, і середнє по всьому корпусу
    ховає саме те, що цікаво."""
    src = {"tuned": CASES, "held_out": HELD_OUT}.get(part, CASES + HELD_OUT)
    out = []
    for c in src:
        cc = {"ptype": PHP, "ok": set(), "not_ours": False, **c}
        if ptype is None or cc["ptype"] == ptype:
            out.append(cc)
    return out


def score(case: dict, picked) -> dict:
    """Один кейс проти одного набору чеків.

    `hit` — знайдено ВСЕ, без чого скаргу не полагодиш. Це і є головна
    цифра: роутер працює на повноту, тому часткове влучання — все одно
    промах, просто не такий помітний.
    """
    got = set(picked)
    must, ok = set(case["must"]), set(case["ok"])
    return {
        "hit": must <= got,
        "found": len(must & got),
        "need": len(must),
        "missed": sorted(must - got),
        "noise": sorted(got - must - ok),
        "picked": len(got),
    }


def summary(rows: list[dict]) -> dict:
    """Підсумок по корпусу. `recall` рахуємо по ЧЕКАХ, а не по кейсах:
    інакше розмита скарга з трьома обов'язковими чеками важила б стільки ж,
    скільки точна з одним."""
    need = sum(r["need"] for r in rows)
    found = sum(r["found"] for r in rows)
    full = sum(1 for r in rows if r["hit"])
    return {
        "cases": len(rows),
        "full_hits": full,
        "recall": round(found / max(1, need), 3),
        "noise_avg": round(sum(len(r["noise"]) for r in rows) / max(1, len(rows)), 2),
        "picked_avg": round(sum(r["picked"] for r in rows) / max(1, len(rows)), 2),
    }
