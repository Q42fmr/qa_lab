from __future__ import annotations

import re


def _norm(s: str) -> str:
    """Нижній регістр, ё→е, схлопнуті пробіли.

    ё→е з обох боків навмисно: у їхніх літералах «Мёртвые», «чёрном»,
    «Вёрстка», і варто комусь передрукувати рядок через «е» — якір мовчки
    перестав би матчити.
    """
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е")).strip()


# ⚠️ Константи проганяємо через `_norm` ТУТ, а не пишемо нормалізованими
# руками. Інакше повторюється помилка, на якій цей файл уже попався:
# «Всё ок» лишилось з `ё`, а звірялось із текстом, де `ё` вже стала `е`, —
# і гілка не спрацьовувала мовчки. Літерал лишаємо в тому вигляді, як він
# стоїть у них: так його можна знайти грепом у їхньому коді.
SOFT_HEADER = _norm("Посмотреть глазами (не дефект")
ALL_OK = _norm("Всё ок")

# `advice_text()`: перший рядок несе домен.
_HEADER_RX = re.compile(r"^что фиксить\s*[—–-]\s*(\S+)", re.I)

# Рядок вердикту: «• [главная] текст» або «👁 [/kontakt] текст».
_LINE_RX = re.compile(r"^[•👁\-\s]*(?:\[([^\]]{1,40})\]\s*)?(.+)$")

# Фолбек самого TSM для невідомої перевірки: «имя_проверки: лог».
# Цифри в імені дозволені: наступна їхня перевірка цілком може називатись
# `spellcheck2`, і саме такі — нові — нам тут і потрібні. Кирилиця під клас
