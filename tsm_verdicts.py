# Довші якорі перші: «Убрать банковские реквизиты», «Убрать заявленное
# партнёрство» і «Убрать рисковый…» починаються однаково.
_SORTED = sorted(VERDICTS, key=lambda v: -len(v["anchor"]))
_NORMED = [(_norm(v["anchor"]), v) for v in _SORTED]


def match_line(line: str) -> dict | None:
    """Вердикт за одним рядком або None."""
    n = _norm(line)
    for anchor, v in _NORMED:
        if n.startswith(anchor):
            return v
    return None


def parse(text: str) -> dict:
    """Розбір коментаря TSM.

    Повертає:
      `domain`  — з рядка «Что фиксить — X», якщо він є;
      `items`   — впізнані вердикти (жовті позначені `soft`);
      `rest`    — рядки, які на вердикт не схожі: людська проза. Саме вони
                  йдуть далі в слова і в модель;
      `unknown` — рядки, які СХОЖІ на вердикт (маркер або «имя_проверки: …»),
                  але не впізнані, у вигляді `{"line", "tsm"}`. Ненульове =
                  їхній `advice.py` розійшовся з нашими якорями, час
                  перечитати (Ф7). `tsm` заповнене там, де рядок сам себе
                  назвав, — тоді видно, ЯКУ перевірку дописувати в мапу;
      `all_ok`  — TSM сказав «фіксити нема чого».
    """
    out = {"domain": "", "items": [], "rest": [], "unknown": [], "all_ok": False}
    soft = False
    for raw in (text or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        n = _norm(line)
        if not out["domain"]:
            m = _HEADER_RX.match(n)
            if m:
                out["domain"] = m.group(1).strip(" .,;")
                continue
        if n.startswith(ALL_OK):
            out["all_ok"] = True
            continue
        if SOFT_HEADER in n:
            soft = True                      # усе нижче — «глянути очима»
            continue
        m = _LINE_RX.match(line)
        page, body = (m.group(1) or "", m.group(2)) if m else ("", line)
        v = match_line(body)
        if v:
            out["items"].append({**v, "page": page, "line": body, "soft": soft})
            continue
        # Схоже на вердикт, але не впізнане: маркер на початку або їхній
        # фолбек «имя_проверки: лог». Це не проза — це дрейф.
        m2 = _RAW_RX.match(_norm(body))
        if raw.lstrip().startswith(("•", "👁")) or m2:
            # Ім'я перевірки, якщо воно є. `_advise_check` віддає
            # `f"{name}: логи"` для перевірки, у якої гілки поради немає —
            # тобто ЇХНЯ нова перевірка сама називає себе. Без цього дрейф
            # виглядає як «щось не розібрали», а з ним — як «допиши мапу
            # для spellcheck2».
            out["unknown"].append({"line": body, "tsm": m2.group(1) if m2 else ""})
            continue
        out["rest"].append(line)
    return out


def checks_for(items: list[dict], available) -> list[str]:
    """Наші чеки за впізнаними вердиктами, звужені до наявних.

    `available` — id з КАТАЛОГУ поточного проєкту, тобто вже відфільтровані
    і за типом (php/node), і за вимкненими скілами. Тому тип проєкту сюди
    передавати не треба: беремо обидві гілки мапи й лишаємо те, що в цьому
    проєкті існує. Заразом це виконує правило «вимкнений скіл ховає чек» —
    детермінований шлях не має бути дірою в ньому.

    Жовте (`soft`) не роутиться ніколи.
    """
    ids = set(available)
    seen, out = set(), []
    for it in items:
        if it.get("soft"):
            continue
        for cid in (it.get("php") or []) + (it.get("node") or []):
            if cid in ids and cid not in seen:
                seen.add(cid)
                out.append(cid)
    return out


def outcome(items: list[dict], available) -> dict:
    """Підсумок по розібраному коментарю — що з цим робити.

    Порядок важливий: збій тули б'є все інше. Якщо прогін TSM зірвався, то
    червоне, що стоїть після нього в тому ж тексті, стосується недоперевіреної
    сторінки — у їхньому ж коментарі до `page_guard` так і написано: «вердикты,
    идущие после этого места, относятся к ЧУЖОЙ странице».
    """
    hard = [i for i in items if not i.get("soft")]
    return {
        "tool_failure": [i for i in hard if i.get("tool_failure")],
        "checks": checks_for(items, available),
        "not_ours": [i for i in hard if i.get("not_ours")],
        "no_check": [i for i in hard if i.get("no_check")],
        "visual": [i for i in hard if i.get("visual")],
        "soft": [i for i in items if i.get("soft")],
    }

