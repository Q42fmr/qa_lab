# Довші перші: «Убрать банковские реквизиты» і «Убрать со страницы банковские
# реквизиты» починаються однаково, і коротший забрав би обидва.
_NAME_PREFIXES = sorted(
    ((_norm(ph), name) for name, phrases in NAMES.items() for ph in phrases),
    key=lambda x: -len(x[0]))


def name_of_line(line: str) -> str:
    """Ім'я їхньої перевірки за одним рядком поради. Порожньо — не впізнали.

    Це заміна старому «фраза → наші чеки»: далі рядок іде в `verdict_map` і
    роутиться там разом зі структурованим входом, одним шляхом.
    """
    n = _norm(line)
    if not n:
        return ""
    for prefix, name in _NAME_PREFIXES:
        if n.startswith(prefix):
            return name
    return ""
